package com.example.core.ai

import android.util.Log
import com.google.firebase.Firebase
import com.google.firebase.ai.ai
import com.google.firebase.ai.type.generationConfig
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeout

private const val TAG = "MediCoreGeminiService"

/**
 * MediCore Gemini AI Service using Firebase AI Logic (`Firebase.ai`).
 * Connects directly to the Gemini API with App Check attestation without client-side API keys.
 * Uses gemini-3.8-flash for clinical notes assistance, medical summarization, and patient triage queries.
 */
class MediCoreGeminiService {

    // Lazy initialization of gemini-3.8-flash to prevent class-loading crashes before App Check runs
    private val model by lazy {
        Firebase.ai.generativeModel(
            modelName = "gemini-3.8-flash",
            generationConfig = generationConfig {
                temperature = 0.2f // Controlled, factual clinical assistance
            }
        )
    }

    /**
     * Unary content generation with realistic 60s timeout for clinical analysis.
     */
    suspend fun generateClinicalGuidance(prompt: String): String = withContext(Dispatchers.IO) {
        try {
            withTimeout(60_000L) {
                val response = model.generateContent(prompt)
                response.text ?: "No guidance generated by Gemini model."
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Gemini generation failed: ${e.message}", e)
            "Gemini AI Assistant Note: ${e.localizedMessage ?: "Inference temporarily unavailable. Please retry with network connectivity."}"
        }
    }

    /**
     * Streaming generation for responsive clinical chat and long-form SOAP notes.
     */
    fun streamClinicalDraft(prompt: String): Flow<String> = flow {
        withTimeout(60_000L) {
            val responseStream = model.generateContentStream(prompt)
            responseStream.collect { chunk ->
                chunk.text?.let { emit(it) }
            }
        }
    }
}
